import assert from 'node:assert/strict';
import { parseWorkbook } from '../src/lib/xlsx-parser';
import { parseItsmWorkbook } from '../src/lib/itsm-parser';
import { correlateItsm } from '../src/lib/itsm-correlation';

const buffer = (text: string) => new TextEncoder().encode(text).buffer;
const alerts = parseWorkbook(buffer('Relatório de alarmes\r\n"Alarme";"Dispositivo";"Responsável";"Horário Inicial";"Horário Final";"Comentário"\r\n"ICMP";"LINK-A";"noc-solor";"01/10/2026 10:00:00";"01/10/2026 11:00:00";"#JIRA:INC-1#"'), 'alerts.csv');
assert.equal(alerts.records.length, 1);
assert.equal(alerts.records[0].durationMinutes, 60);
assert.equal(alerts.records[0].comment, '#JIRA:INC-1#');
const incidents = parseItsmWorkbook(buffer('Chave da item,Resumo,Criado,Atualizado(a),Comentários,Comentários\nINC-1,LINK-A,01/out/26 10:00 AM,01/out/26 11:00 AM,"primeiro\ncomentário",segundo'), 'incidents.csv');
assert.equal(incidents.records[0].comments?.length, 2);
const subtasks = parseItsmWorkbook(buffer('Chave da item,Pai,Motivo do alarme,Atualizado(a)\nINC-2,INC-1,Energia,01/out/26 11:00 AM\nINC-2,INC-1,Energia,01/out/26 12:00 PM\nINC-3,INC-1,Fibra,01/out/26 12:00 PM\nINC-4,,,01/out/26 12:00 PM'), 'subtasks.csv');
assert.equal(subtasks.records[0].parentKey, 'INC-1');
const result = correlateItsm(alerts.records, incidents.records, subtasks.records);
assert.equal(result.incidents.length, 1);
assert.equal(result.subtasks.length, 3);
assert.equal(result.linkedAlerts, 1);
assert.equal(result.linkedSubtasks, 2);
assert.equal(result.conflictingIncidents, 1);
assert.equal(result.reasons.find(r => r.name === 'Energia')?.subtasks, 1);
assert.equal(result.reasons.find(r => r.name === 'Fibra')?.incidents, 1);
assert.equal(result.rows[0].durationMinutes, 60);
assert.equal(result.rows[0].reasonStatus, 'conflicting');
const missing = correlateItsm(alerts.records, incidents.records, []);
assert.equal(missing.rows[0].reasonStatus, 'missing');
assert.equal(missing.reasons.length, 0);
const latin = Uint8Array.from(Buffer.from('Alarme;Dispositivo;Respons\xe1vel;Hor\xe1rio Inicial;Hor\xe1rio Final\nICMP;LINK-A;Jo\xe3o;01/10/2026 10:00:00;01/10/2026 11:00:00', 'latin1'));
assert.equal(parseWorkbook(latin.buffer, 'latin.csv').records[0].responsible, 'João');
assert.throws(() => parseWorkbook(buffer('Alarme;Dispositivo\n"aberto'), 'bad.csv'));
console.log('CSV and correlation: all assertions passed');
const legacy = 'Alarme;Dispositivo;Responsável;Horário Inicial;Horário Final;Comentário\nICMP;LINK-A;noc-solor;01/10/2026 10:00:00;01/10/2026 11:00:00;"Texto \\"citado\nsegunda linha\\""';
assert.equal(parseWorkbook(buffer(legacy), 'legacy.csv').records[0].comment, 'Texto "citado\nsegunda linha"');
const footer = parseWorkbook(buffer('Alarme;Dispositivo;Responsável;Horário Inicial;Horário Final\nICMP;LINK-A;noc-solor;01/10/2026 10:00:00;01/10/2026 11:00:00\nTotal: 1;;;;'), 'footer.csv');
assert.equal(footer.totalRows, 1, 'A linha de total do relatório não é um alerta');
const jiraIds = parseItsmWorkbook(buffer('Chave da item,ID da item,Resumo\nINC-1,100,Ativo'), 'ids.csv');
const jiraCustom = parseItsmWorkbook(buffer('Chave da item,Parent id,Campo personalizado (Motivo do alarme)\nINC-2,100,Energia'), 'custom.csv');
assert.equal(correlateItsm(alerts.records, jiraIds.records, jiraCustom.records).linkedSubtasks, 1);
assert.equal(jiraCustom.records[0].reason, 'Energia');
const multipleIncidents = parseItsmWorkbook(buffer('Chave da item,ID da item,Motivo\nINC-1,100,\nINC-9,900,Fibra'), 'multiple.csv');
const oneReasonSub = parseItsmWorkbook(buffer('Chave da item,Pai,Motivo\nINC-2,INC-1,Energia'), 'one.csv');
const multipleAlerts = [{ ...alerts.records[0], comment: 'INC-1 INC-9' }];
assert.equal(correlateItsm(multipleAlerts, multipleIncidents.records, oneReasonSub.records).rows[0].reasonStatus, 'conflicting');
const conflictingParent = parseItsmWorkbook(buffer('Chave da item,Pai,Parent id,Motivo\nINC-2,INC-1,900,Energia'), 'conflicting-parent.csv');
assert.equal(correlateItsm(alerts.records, multipleIncidents.records, conflictingParent.records).linkedSubtasks, 0);
const duplicateId = parseItsmWorkbook(buffer('Chave da item,ID da item\nINC-1,100\nINC-9,100'), 'duplicate-id.csv');
assert.equal(correlateItsm(alerts.records, duplicateId.records, jiraCustom.records).linkedSubtasks, 0);
